/** 随机抽一对；exclude 用于避免连续两轮同一大众词 */
export function pickWordPair(exclude?: string): WordPair {
  const pool = WORD_PAIRS.filter((p) => p.common !== exclude);
  const list = pool.length > 0 ? pool : WORD_PAIRS;
  return list[Math.floor(Math.random() * list.length)]!;
}
