/** 从指定类型的卡池随机抽一张 */
export function pickCard(kind: CardKind): Card {
  const pool = kind === 'truth' ? TRUTH_CARDS : DARE_CARDS;
  return { kind, text: pool[Math.floor(Math.random() * pool.length)]! };
}

