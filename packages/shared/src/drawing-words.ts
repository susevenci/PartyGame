/** 随机抽题，避免与上一题相同 */
export function pickDrawingWord(exclude?: string): string {
  const pool = DRAWING_WORDS.filter((w) => w !== exclude);
  const list = pool.length > 0 ? pool : DRAWING_WORDS;
  return list[Math.floor(Math.random() * list.length)]!;
}
