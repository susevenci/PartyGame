/** 随机取一个字，尽量避开 used 中已出现的题面 */
export function pickBombPartyPrompt(used: string[] = []): string {
  const fresh = BOMBPARTY_PROMPTS.filter((p) => !used.includes(p));
  const pool = fresh.length > 0 ? fresh : BOMBPARTY_PROMPTS;
  return pool[Math.floor(Math.random() * pool.length)]!;
}
